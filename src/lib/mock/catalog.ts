function brandName(slug: string): string {
  return brands.find((brand) => brand.slug === slug)?.name ?? slug;
}

const color = (label: string, swatch: string): AttributeValue => ({ label, swatch });

const sizeAttr = (labels: string[]): ProductAttribute => ({
  name: "Size",
  style: "button",
  values: labels.map((label) => ({ label })),
});

const colorAttr = (values: AttributeValue[]): ProductAttribute => ({
  name: "Color",
  style: "swatch",
  values,
});

type SimpleInput = {
  id: string;
  slug: string;
  name: string;
  brandSlug: string;
  categorySlug: string;
  price: number;
  salePrice: number | null;
  stock: number;
  sku: string;
  rating: number;
  reviewCount: number;
  imageHue: number;
  shortDescription: string;
  description: string;
  warranty: string;
  returns: string;
  featured?: boolean;
  bestSeller?: boolean;
  isNew?: boolean;
  flashSale?: boolean;
  createdAt: string;
};

function simpleProduct(input: SimpleInput): Product {
  const variant = createSimpleVariant({
    id: `${input.id}-default`,
    sku: input.sku,
    price: input.price,
    salePrice: input.salePrice,
    stock: input.stock,
    imageHue: input.imageHue,
  });

  return {
    id: input.id,
    slug: input.slug,
    name: input.name,
    brandSlug: input.brandSlug,
    brandName: brandName(input.brandSlug),
    categorySlug: input.categorySlug,
    rating: input.rating,
    reviewCount: input.reviewCount,
    imageHue: input.imageHue,
    images: [],
    shortDescription: input.shortDescription,
    description: input.description,
    warranty: input.warranty,
    returns: input.returns,
    videoUrl: "",
    featured: input.featured ?? false,
    bestSeller: input.bestSeller ?? false,
    isNew: input.isNew ?? false,
    flashSale: input.flashSale ?? false,
    createdAt: input.createdAt,
    attributes: [],
    variants: [variant],
  };
}

